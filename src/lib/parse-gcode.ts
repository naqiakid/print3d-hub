export interface GcodeStats {
  weight_g:    number | null
  print_hours: number | null
  layer_count: number | null
  slicer:      string | null

  // Slicing & Resolution Specs
  layer_height?:       number | null  // e.g. 0.16 (mm)
  first_layer_height?: number | null  // e.g. 0.16 (mm)
  
  // Infill & Shell Architecture
  infill_density?:     number | null  // e.g. 15 (%)
  infill_pattern?:     string | null  // e.g. 'crosshatch', 'gyroid', 'grid'
  wall_loops?:         number | null  // e.g. 2, 3
  wall_generator?:     string | null  // e.g. 'arachne', 'classic'
  top_layers?:         number | null  // e.g. 6
  bottom_layers?:      number | null  // e.g. 4

  // Bed Adhesion & Brim
  brim_type?:          string | null  // e.g. 'brim_ears', 'outer_only', 'auto'
  brim_width?:         number | null  // e.g. 5 (mm)

  // Thermals & Material
  nozzle_temp?:        number | null  // e.g. 220 (°C)
  bed_temp?:           number | null  // e.g. 40 (°C)
  filament_type?:      string | null  // e.g. 'PLA', 'PETG'
  supports_enabled?:   boolean | null // e.g. true
  support_type?:       string | null  // e.g. 'tree', 'normal'
}

// Read the header (first 96 KB) and footer (last 96 KB) of a gcode file —
// all slicer metadata and configuration dumps are located in these regions.
export async function parseGcodeFile(file: File): Promise<GcodeStats> {
  const HEAD = 98_304   // 96 KB
  const TAIL = 98_304   // 96 KB
  const [headText, tailText] = await Promise.all([
    file.slice(0, HEAD).text(),
    file.slice(Math.max(0, file.size - TAIL)).text(),
  ])
  return parseGcodeText(`${headText}\n${tailText}`)
}

export function parseGcodeText(content: string): GcodeStats {
  let weight_g:           number | null = null
  let print_hours:        number | null = null
  let layer_count:        number | null = null
  let slicer:             string | null = null
  let layer_height:       number | null = null
  let first_layer_height: number | null = null
  let infill_density:     number | null = null
  let infill_pattern:     string | null = null
  let wall_loops:         number | null = null
  let wall_generator:     string | null = null
  let top_layers:         number | null = null
  let bottom_layers:      number | null = null
  let brim_type:          string | null = null
  let brim_width:         number | null = null
  let nozzle_temp:        number | null = null
  let bed_temp:           number | null = null
  let filament_type:      string | null = null
  let supports_enabled:   boolean | null = null
  let support_type:       string | null = null

  for (const raw of content.split('\n')) {
    const line = raw.trim()
    if (!line.startsWith(';')) continue

    // Detect Slicer Software
    if (!slicer) {
      if (/generated by OrcaSlicer/i.test(line))       slicer = 'OrcaSlicer'
      else if (/generated by PrusaSlicer/i.test(line)) slicer = 'PrusaSlicer'
      else if (/generated by SuperSlicer/i.test(line)) slicer = 'SuperSlicer'
      else if (/generated by BambuStudio/i.test(line)) slicer = 'BambuStudio'
      else if (/Generated with Cura/i.test(line))      slicer = 'Cura'
      else if (/Sliced by ideaMaker/i.test(line))      slicer = 'IdeaMaker'
      else if (/Simplify3D/i.test(line))               slicer = 'Simplify3D'
    }

    // Filament Weight & Length
    if (weight_g === null) {
      const mTotal = line.match(/;\s*total\s+filament\s+used\s*\[g\]\s*=\s*([\d.]+)/i)
      if (mTotal) { weight_g = parseFloat(mTotal[1]); continue }
      const mG = line.match(/;\s*filament\s+used\s*\[g\]\s*=\s*([\d.]+)/i)
      if (mG) { weight_g = parseFloat(mG[1]); continue }
      const mW = line.match(/;\s*filament\s+weight\s*[=:]\s*([\d.]+)\s*g?/i)
      if (mW) { weight_g = parseFloat(mW[1]); continue }
      // Meters → grams (1.75mm PLA ~2.98 g/m)
      const mM = line.match(/;Filament\s+used\s*:\s*([\d.]+)\s*m\b/i)
      if (mM) { weight_g = Math.round(parseFloat(mM[1]) * 2.98 * 10) / 10; continue }
    }

    // Print Time
    if (print_hours === null) {
      const mPrusa = line.match(/;\s*estimated\s+printing\s+time(?:\s*\([^)]*\))?\s*=\s*(.+)/i)
      if (mPrusa) { print_hours = toHours(parseTimeStr(mPrusa[1])); continue }
      const mPrintTime = line.match(/;PRINT\.TIME\s*:\s*([\d.]+)/i)
      if (mPrintTime) { print_hours = toHours(parseFloat(mPrintTime[1]) / 3600); continue }
      const mTime = line.match(/^;TIME\s*:\s*([\d.]+)/i)
      if (mTime) { print_hours = toHours(parseFloat(mTime[1]) / 3600); continue }
      const mBuild = line.match(/;\s*Build\s+time\s*:\s*(.+)/i)
      if (mBuild) { print_hours = toHours(parseTimeStr(mBuild[1])); continue }
    }

    // Total Layers
    if (layer_count === null) {
      const mLC = line.match(/;\s*layer_count\s*=\s*(\d+)/i)
               ?? line.match(/;Layer\s+count\s*:\s*(\d+)/i)
               ?? line.match(/;\s*total\s+layer\s+(?:number|count)\s*[:=]\s*(\d+)/i)
      if (mLC) { layer_count = parseInt(mLC[1]); continue }
    }

    // Infill Density & Pattern
    if (infill_density === null) {
      const mID = line.match(/;\s*(?:sparse_infill_density|fill_density|infill_density)\s*=\s*([\d.]+)%?/i)
      if (mID) { infill_density = parseFloat(mID[1]) }
    }
    if (infill_pattern === null) {
      const mIP = line.match(/;\s*(?:sparse_infill_pattern|fill_pattern|infill_pattern)\s*=\s*([a-zA-Z0-9_-]+)/i)
      if (mIP) { infill_pattern = mIP[1].toLowerCase() }
    }

    // Walls / Perimeters / Shells
    if (wall_loops === null) {
      const mWL = line.match(/;\s*(?:wall_loops|perimeters|wall_line_count)\s*=\s*(\d+)/i)
      if (mWL) { wall_loops = parseInt(mWL[1], 10) }
    }
    if (wall_generator === null) {
      const mWG = line.match(/;\s*wall_generator\s*=\s*([a-zA-Z0-9_-]+)/i)
      if (mWG) { wall_generator = mWG[1].toLowerCase() }
    }
    if (top_layers === null) {
      const mTL = line.match(/;\s*(?:top_shell_layers|top_solid_layers)\s*=\s*(\d+)/i)
      if (mTL) { top_layers = parseInt(mTL[1], 10) }
    }
    if (bottom_layers === null) {
      const mBL = line.match(/;\s*(?:bottom_shell_layers|bottom_solid_layers)\s*=\s*(\d+)/i)
      if (mBL) { bottom_layers = parseInt(mBL[1], 10) }
    }

    // Layer Height
    if (layer_height === null) {
      const mLH = line.match(/;\s*(?:layer_height|Layer height)\s*[:=]\s*([\d.]+)/i)
      if (mLH) { layer_height = parseFloat(mLH[1]) }
    }
    if (first_layer_height === null) {
      const mFLH = line.match(/;\s*first_layer_height\s*[:=]\s*([\d.]+)/i)
      if (mFLH) { first_layer_height = parseFloat(mFLH[1]) }
    }

    // Brim & Bed Adhesion
    if (brim_type === null) {
      const mBT = line.match(/;\s*brim_type\s*=\s*([a-zA-Z0-9_-]+)/i)
      if (mBT) { brim_type = mBT[1].toLowerCase() }
    }
    if (brim_width === null) {
      const mBW = line.match(/;\s*brim_width\s*=\s*([\d.]+)/i)
      if (mBW) { brim_width = parseFloat(mBW[1]) }
    }

    // Temperatures
    if (nozzle_temp === null) {
      const mNT = line.match(/;\s*(?:first_layer_temperature|nozzle_temperature|temperature)\s*=\s*(\d+)/i)
      if (mNT) { nozzle_temp = parseInt(mNT[1], 10) }
    }
    if (bed_temp === null) {
      const mBT = line.match(/;\s*(?:first_layer_bed_temperature|bed_temperature)\s*=\s*(\d+)/i)
      if (mBT) { bed_temp = parseInt(mBT[1], 10) }
    }

    // Filament Type & Support Structures
    if (filament_type === null) {
      const mFT = line.match(/;\s*filament_type\s*=\s*([a-zA-Z0-9_+]+)/i)
      if (mFT) { filament_type = mFT[1].split(';')[0].trim() }
    }
    if (supports_enabled === null) {
      if (/;\s*enable_support\s*=\s*1/i.test(line) || /;\s*support_material\s*=\s*1/i.test(line) || /;TYPE:Support/i.test(line)) {
        supports_enabled = true
      }
    }
    if (support_type === null) {
      const mST = line.match(/;\s*support_type\s*=\s*([a-zA-Z0-9_(). -]+)/i)
      if (mST) {
        support_type = mST[1].trim().toLowerCase().replace('tree(auto)', 'tree (auto)')
      } else if (/tree/i.test(line)) {
        support_type = 'tree'
      }
    }
  }

  return {
    weight_g,
    print_hours,
    layer_count,
    slicer,
    layer_height,
    first_layer_height,
    infill_density,
    infill_pattern,
    wall_loops,
    wall_generator,
    top_layers,
    bottom_layers,
    brim_type,
    brim_width,
    nozzle_temp,
    bed_temp,
    filament_type,
    supports_enabled,
    support_type,
  }
}

function parseTimeStr(s: string): number {
  let secs = 0
  const h   = s.match(/(\d+)\s*h/i)
  const m   = s.match(/(\d+)\s*m(?!s)/i)
  const sec = s.match(/(\d+)\s*s/i)
  if (h)   secs += parseInt(h[1]) * 3600
  if (m)   secs += parseInt(m[1]) * 60
  if (sec) secs += parseInt(sec[1])
  return secs / 3600
}

function toHours(h: number): number {
  return Math.round(h * 10) / 10
}

export interface ManufacturingPassport {
  hasGcodeSpecs: boolean
  slicer: string | null
  layerHeight: number | null
  layerCount: number | null
  infillDensity: number | null
  infillPattern: string | null
  wallLoops: number | null
  wallGenerator: string | null
  topLayers: number | null
  bottomLayers: number | null
  brimType: string | null
  brimWidth: number | null
  nozzleTemp: number | null
  bedTemp: number | null
  supportsEnabled: boolean
  supportType: string | null
  weightG: number | null
  printHours: number | null
}

export function extractManufacturingPassport(request: {
  plate_filaments?: Array<{
    material?: string
    color?: string
    color_hex?: string
    weight_g?: number | null
    infill_density?: number | null
    infill_pattern?: string | null
    wall_loops?: number | null
    wall_generator?: string | null
    layer_height?: number | null
    brim_type?: string | null
    brim_width?: number | null
    nozzle_temp?: number | null
    bed_temp?: number | null
    slicer?: string | null
    top_layers?: number | null
    bottom_layers?: number | null
    supports_enabled?: boolean | null
    support_type?: string | null
  }> | null
  quote_message?: string | null
  notes?: string | null
  weight_g?: number | null
  print_hours?: number | null
  supports?: boolean | null
  custom_infill?: number | null
  custom_wall_count?: number | null
  confirmed_addons?: string[] | null
}): ManufacturingPassport {
  const plate = request.plate_filaments?.[0]
  const qMsg = request.quote_message || ''
  const notes = request.notes || ''
  const combinedText = `${qMsg} ${notes}`

  // Slicer
  const slicerMatch = combinedText.match(/Sliced (?:in|via|with)\s+([a-zA-Z0-9_.\s]+?)(?: at| ·|\(|,|$)/i)
  const slicer = plate?.slicer || (slicerMatch ? slicerMatch[1].trim() : null)

  // Layer Height
  const lhMatch = combinedText.match(/([\d.]+)mm\s+layer(?:\s+height)?/i)
  const layerHeight = plate?.layer_height ?? (lhMatch ? parseFloat(lhMatch[1]) : null)

  // Layer Count
  const lcMatch = combinedText.match(/(\d+)\s+layers/i)
  const layerCount = lcMatch ? parseInt(lcMatch[1], 10) : null

  // Infill Density & Pattern
  const infillMatch = combinedText.match(/(\d+)%\s*(?:([a-zA-Z0-9_-]+)\s+)?infill/i)
  const infillDensity = plate?.infill_density ?? (infillMatch ? parseInt(infillMatch[1], 10) : request.custom_infill ?? null)
  const infillPattern = plate?.infill_pattern ?? (infillMatch && infillMatch[2] ? infillMatch[2].toLowerCase() : null)

  // Walls
  const wallMatch = combinedText.match(/(\d+)\s+walls?(?:\s*\(([a-zA-Z0-9_-]+)\))?/i)
  const wallLoops = plate?.wall_loops ?? (wallMatch ? parseInt(wallMatch[1], 10) : request.custom_wall_count ?? null)
  const wallGenerator = plate?.wall_generator ?? (wallMatch && wallMatch[2] ? wallMatch[2].toLowerCase() : null)

  // Brim
  const brimMatch = combinedText.match(/([\d.]+mm\s+)?(brim[_\s]ears|mouse[_\s]ears|outer[_\s]only|auto[_\s]brim|brim)/i)
  const brimType = plate?.brim_type ?? (brimMatch ? brimMatch[2].replace(/\s+/g, '_').toLowerCase() : null)
  const brimWidth = plate?.brim_width ?? (brimMatch && brimMatch[1] ? parseFloat(brimMatch[1]) : (brimType ? 5 : null))

  // Temperatures
  const nozzleMatch = combinedText.match(/(\d+)°C\s+nozzle/i)
  const nozzleTemp = plate?.nozzle_temp ?? (nozzleMatch ? parseInt(nozzleMatch[1], 10) : null)

  const bedMatch = combinedText.match(/(\d+)°C\s+bed/i)
  const bedTemp = plate?.bed_temp ?? (bedMatch ? parseInt(bedMatch[1], 10) : null)

  // Supports
  const supportsConfirmed = Boolean(
    plate?.supports_enabled ||
    request.supports ||
    request.confirmed_addons?.includes('supports') ||
    /tree\s+support|support\s+enabled/i.test(combinedText)
  )
  const supportType = plate?.support_type || (/tree/i.test(combinedText) ? 'tree' : supportsConfirmed ? 'normal' : null)

  const hasGcodeSpecs = Boolean(
    slicer ||
    layerHeight ||
    infillPattern ||
    wallLoops ||
    brimType ||
    nozzleTemp ||
    bedTemp ||
    (plate && (plate.infill_density || plate.wall_loops || plate.brim_type))
  )

  return {
    hasGcodeSpecs,
    slicer,
    layerHeight,
    layerCount,
    infillDensity,
    infillPattern,
    wallLoops,
    wallGenerator,
    topLayers: plate?.top_layers ?? null,
    bottomLayers: plate?.bottom_layers ?? null,
    brimType,
    brimWidth,
    nozzleTemp,
    bedTemp,
    supportsEnabled: Boolean(supportsConfirmed),
    supportType,
    weightG: request.weight_g ?? plate?.weight_g ?? null,
    printHours: request.print_hours ?? null,
  }
}
